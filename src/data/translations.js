/** Nuqta bilan yozilgan yo'lni obyektdan olib beradi: getPath(obj, "nav.home") */
export function getPath(source, path) {
  if (!source) return undefined
  return path.split(".").reduce((acc, key) => (acc == null ? acc : acc[key]), source)
}

/** Berilgan til uchun tarjima funksiyasini qaytaradi (topilmasa o'zbek tiliga qaytadi). */
export function createTranslator(lang) {
  const primary = translations[lang] || translations[DEFAULT_LANGUAGE]
  const fallback = translations[DEFAULT_LANGUAGE]
  return function t(path, fallbackText) {
    const value = getPath(primary, path)
    if (value !== undefined && value !== null) return value
    const backup = getPath(fallback, path)
    if (backup !== undefined && backup !== null) return backup
    return fallbackText !== undefined ? fallbackText : path
  }
}

